//! Notifications, directives, and alert reasons for COP-1 (FOP-1 and FARM-1).
//!
//! Defined in CCSDS 232.1-B-2 Section 4:
//! - Section 4.2 & Table 4-1 / Table 4-2: Management Directives and Directive Notifications.
//! - Section 4.3 & Table 4-4: Alerts and Alert Reasons (COP-004).
//! - Section 4.4 & Table 4-5: Transfer Service Notifications.
//! - Section 5.1.10.3 & Table 7-1: Timeout Type configuration.

use aldis_core::ids::FrameSeqNum;
use aldis_core::time::Duration;
use core::num::NonZeroU8;

use crate::fop1_table::{Fop1Event, Fop1State};

/// FOP-1 Timeout Type parameter (CCSDS 232.1-B-2 §5.1.10.3, Table 7-1; COP-001, COP-013).
///
/// Determines the behavior when timer T1 expires and the transmission limit
/// has been reached:
/// - [`TimeoutType::Tt0`]: generate an Alert and transition to State S6 (Initial).
/// - [`TimeoutType::Tt1`]: suspend the AD service, setting `Suspend_State`, and transition to State S6.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash)]
#[repr(u8)]
pub enum TimeoutType {
    /// Timeout Type 0: generate an Alert when transmission limit is reached.
    Tt0 = 0,
    /// Timeout Type 1: suspend AD service when transmission limit is reached.
    Tt1 = 1,
}

/// FOP-1 Management Directives (CCSDS 232.1-B-2 §4.2, Table 4-1; COP-001, COP-015).
///
/// Management directives control the lifecycle and configuration of the
/// Frame Operation Procedure-1 (FOP-1) state machine.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum Directive {
    /// Initiate AD Service without CLCW Check (CCSDS 232.1-B-2 Table 4-1, Event E23).
    InitiateAdWithoutClcwCheck,
    /// Initiate AD Service with CLCW Check (CCSDS 232.1-B-2 Table 4-1, Event E24).
    InitiateAdWithClcwCheck,
    /// Initiate AD Service with Unlock (CCSDS 232.1-B-2 Table 4-1, Events E25, E26).
    InitiateAdWithUnlock,
    /// Initiate AD Service with Set V(R) (CCSDS 232.1-B-2 Table 4-1, Events E27, E28).
    InitiateAdWithSetVr {
        /// Target sequence number V*(R) for the peer FARM-1.
        v_r: FrameSeqNum,
    },
    /// Terminate AD Service (CCSDS 232.1-B-2 Table 4-1, Event E29).
    TerminateAd,
    /// Resume AD Service (CCSDS 232.1-B-2 Table 4-1, Events E30..E34).
    ResumeAd,
    /// Set V(S) to a specific sequence number V*(S) (CCSDS 232.1-B-2 Table 4-1, Event E35).
    SetVs {
        /// New transmitter sequence number V*(S).
        v_s: FrameSeqNum,
    },
    /// Set Sliding Window Width K (CCSDS 232.1-B-2 Table 4-1, Event E36).
    SetSlidingWindowWidth {
        /// Sliding window width K: 1..=min(255, `Sent_Queue` capacity), else the directive is
        /// invalid, event E40 (COP-015). A plain `u8`, because the upper bound depends on the
        /// `Sent_Queue` capacity of the engine that receives the directive.
        width: u8,
    },
    /// Set `T1_Initial` timeout duration (CCSDS 232.1-B-2 Table 4-1, Event E37).
    SetT1Initial {
        /// Initial timeout duration for timer T1: at least 1 µs, else the directive is invalid,
        /// event E40.
        duration: Duration,
    },
    /// Set `Transmission_Limit` (CCSDS 232.1-B-2 Table 4-1, Event E38).
    SetTransmissionLimit {
        /// Maximum number of transmissions allowed for a frame; 0 is unrepresentable.
        limit: NonZeroU8,
    },
    /// Set `Timeout_Type` (CCSDS 232.1-B-2 Table 4-1, Event E39).
    SetTimeoutType {
        /// Timeout behavior: TT0 (Alert) or TT1 (Suspend).
        timeout_type: TimeoutType,
    },
}

/// Alert reasons generated by FOP-1 (CCSDS 232.1-B-2 §4.3, Table 4-4, COP-004).
///
/// Alerts report serious protocol anomalies that cause FOP-1 to transition
/// to State S6 (Initial) or require operator intervention.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub enum AlertReason {
    /// Transmission limit reached for a Type-AD or Type-BC frame.
    Limit,
    /// Timer T1 expired and transmission limit reached (under TT0), or in State S4/S5.
    T1,
    /// Lockout Flag set to 1 in received CLCW (Event E14).
    Lockout,
    /// Sequence synchronization error between transmitter and receiver (Events E1, E4, E5 in S2/S3).
    Synch,
    /// Invalid N(R) received in CLCW: N(R) outside [NN(R), V(S)] mod 256 (Event E13).
    NnR,
    /// Invalid CLCW received: illegal bit pattern or unexpected flag combination (Events E3, E7, E15).
    Clcw,
    /// Lower-Layer Interface Failure reported by lower procedure (Events E42, E44, E46).
    Llif,
    /// AD service terminated by Terminate AD Service directive (Event E29).
    Term,
}

/// An Alert notification emitted by FOP-1 (CCSDS 232.1-B-2 §4.3, §5.2.15 e, Table 4-4; COP-004).
///
/// It names the reason, the event that caused it, and the state before the event (COP-004).
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub struct Alert {
    /// The reason for the alert.
    pub reason: AlertReason,
    /// The event that triggered the alert (e.g. E13).
    pub event: Fop1Event,
    /// The protocol state before the transition to S6.
    pub prior_state: Fop1State,
}

/// Transfer service notifications for Type-AD and Type-BD requests (CCSDS 232.1-B-2 §4.4, Table
/// 4-5; COP-001, API-083).
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub enum TransferNotification {
    /// Transfer request accepted by FOP-1 for processing.
    Accept,
    /// Transfer request rejected by FOP-1 (e.g. `Wait_Queue` full or lower layer not ready).
    Reject,
    /// Positive confirmation: data successfully transferred (acknowledged by peer FARM-1).
    PositiveConfirm,
    /// Negative confirmation: transfer failed (e.g. queue purged upon termination or alert).
    NegativeConfirm,
}

/// A transfer notification event associating a request handle with its status (CCSDS 232.1-B-2
/// §4.4, Table 4-5; COP-001, API-083).
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub struct TransferNotify<H> {
    /// Handle of the transfer request being acknowledged.
    pub handle: H,
    /// Notification status.
    pub status: TransferNotification,
}

/// Directive service notifications (CCSDS 232.1-B-2 §4.2, Table 4-2; COP-001, API-083).
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub enum DirectiveNotification {
    /// Directive accepted by FOP-1.
    Accept,
    /// Directive rejected by FOP-1 (e.g. invalid directive or invalid state).
    Reject,
    /// Positive confirmation: directive successfully completed.
    PositiveConfirm,
    /// Negative confirmation: directive failed or aborted.
    NegativeConfirm,
}

/// A directive notification event associating a directive handle with its status (CCSDS 232.1-B-2
/// §4.2, Table 4-2; COP-001, API-083).
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub struct DirectiveNotify<H> {
    /// Handle of the directive being acknowledged.
    pub handle: H,
    /// Notification status.
    pub status: DirectiveNotification,
}
