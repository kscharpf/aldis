//! The Markdown of `docs/reference/header-layouts.md`: for each header a table of its fields and
//! a grid of its octets (VER-072).

use std::fmt::Write as _;

use super::probe::{Layout, Placed, ranges};

/// The key of the field at `index` in the grid: `A`-`Z`, then `a`-`z`.
fn key(index: usize) -> char {
    u8::try_from(index)
        .ok()
        .and_then(|i| match i {
            0..=25 => Some(b'A' + i),
            26..=51 => Some(b'a' + (i - 26)),
            _ => None,
        })
        .map_or('?', char::from)
}

/// The anchor GitHub gives a heading: lower case, punctuation dropped, spaces as hyphens.
fn github_slug(title: &str) -> String {
    title
        .to_lowercase()
        .chars()
        .filter(|c| c.is_alphanumeric() || matches!(c, ' ' | '-' | '_'))
        .map(|c| if c == ' ' { '-' } else { c })
        .collect()
}

/// `first–last` or `first`, the runs of `bits` separated by commas.
pub fn bit_ranges(bits: &[usize]) -> String {
    ranges(bits)
        .iter()
        .map(|&(a, b)| {
            if a == b {
                a.to_string()
            } else {
                format!("{a}–{b}")
            }
        })
        .collect::<Vec<_>>()
        .join(", ")
}

/// The table of the fields of `layout`.
fn table(layout: &Layout, out: &mut String) {
    out.push_str("| Key | Field | Bits | Width | Code | Clause |\n|---|---|---|---|---|---|\n");
    for (i, f) in layout.fields.iter().enumerate() {
        let code =
            f.id.map_or_else(|| "–".to_owned(), |(c, n)| format!("{c} `{n}`"));
        let _ = writeln!(
            out,
            "| {} | {} | {} | {} | {} | {} |",
            key(i),
            f.name,
            bit_ranges(&f.bits),
            f.bits.len(),
            code,
            f.clause
        );
    }
}

/// The key of the field that owns `bit`.
fn owner(fields: &[Placed], bit: usize) -> char {
    fields
        .iter()
        .position(|f| f.bits.contains(&bit))
        .map_or('?', key)
}

/// The grid of `layout`: one row per octet, one column per bit of the octet, bit 0 the most
/// significant.
fn grid(layout: &Layout, out: &mut String) {
    out.push_str("```text\noctet  bit  0 1 2 3 4 5 6 7\n");
    for octet in 0..layout.bits.div_ceil(8) {
        let cells: Vec<String> = (0..8)
            .map(|j| owner(&layout.fields, octet * 8 + j).to_string())
            .collect();
        let _ = writeln!(out, "{octet:>5}  {:>3}  {}", octet * 8, cells.join(" "));
    }
    out.push_str("```\n");
}

/// The document: the header, then one section for each layout.
pub fn document(layouts: &[Layout]) -> String {
    let mut out = String::new();
    out.push_str(
        "<!-- Generated by `cargo xtask layouts --write`. Do not edit: change the codec or the \
list of probed fields in `xtask/src/layouts/headers.rs`, and regenerate. -->\n\n",
    );
    out.push_str("# Header layouts\n\n");
    out.push_str(
        "Generated by `cargo xtask layouts --write` (VER-072); `cargo xtask layouts` and `cargo \
xtask ci` check that this file is current. Each layout is derived from the encoders and decoders \
of the codec crates, not from a second table: the probe encodes a header, changes one field at \
a time, and records which bits change. A field the encoder never changes (a version number, a \
reserved spare) takes the bits for which the decoder rejects a change, naming the field. The \
probe fails if two fields share a bit or a bit belongs to no field. The field names, codes, and \
clauses are those of the rustdoc of the items ([RS-015](../06-verification.md)) and of the field \
catalogue ([03 §9.1](../03-api-model.md#91-field-codes)).\n\n",
    );
    out.push_str(
        "Bits are numbered as the Blue Books number them: bit 0 is the most significant bit of \
the first octet. A bit range of `first–last` runs over consecutive bits; a field in several \
ranges is split in the header. The clauses cite the Blue Books by document number; this file \
quotes none of their text or figures.\n\n",
    );
    out.push_str(
        "Not covered: the AOS edition of Issue 4 and earlier (bits 42–43 are a reserved spare), \
the M_PDU and B_PDU headers, the FHEC and OCF fields beyond what the headers above show, the \
extension octets of a P-field and the P-field of an agency-defined code (their bits are \
defined by the agency or by the code), and the ASCII time codes, to which `aldis-time` gives no P-field.\n\n",
    );
    out.push_str("## Contents\n\n");
    for l in layouts {
        let _ = writeln!(out, "- [{}](#{})", l.title, github_slug(l.title));
    }
    out.push('\n');
    for l in layouts {
        let _ = writeln!(out, "## {}\n", l.title);
        let octets = l.bits.div_ceil(8);
        let unit = if octets == 1 { "octet" } else { "octets" };
        let _ = writeln!(out, "{}. {} bits, {octets} {unit}.\n", l.note, l.bits);
        table(l, &mut out);
        out.push('\n');
        grid(l, &mut out);
        out.push('\n');
    }
    out
}

#[cfg(test)]
mod tests {
    use super::{bit_ranges, document, key};
    use crate::layouts::probe::{Layout, Placed};

    fn layout() -> Layout {
        Layout {
            title: "Toy header",
            note: "A toy.",
            bits: 8,
            fields: vec![
                Placed {
                    name: "high",
                    id: Some((1, "spacecraft_id")),
                    clause: "1.0 §1",
                    bits: vec![0, 1, 6, 7],
                },
                Placed {
                    name: "low",
                    id: None,
                    clause: "1.0 §2",
                    bits: vec![2, 3, 4, 5],
                },
            ],
        }
    }

    #[test]
    fn bits_print_in_runs_and_the_grid_shows_the_owner_of_each_bit() {
        // req: VER-072
        assert_eq!(bit_ranges(&[0, 1, 6, 7]), "0–1, 6–7");
        assert_eq!(bit_ranges(&[9]), "9");
        assert_eq!(key(0), 'A');
        assert_eq!(key(26), 'a');
        let doc = document(&[layout()]);
        assert!(
            doc.contains("| A | high | 0–1, 6–7 | 4 | 1 `spacecraft_id` | 1.0 §1 |"),
            "{doc}"
        );
        assert!(doc.contains("    0    0  A A B B B B A A"), "{doc}");
    }
}
